const fs = require("fs");
const path = require("path");

const folder = path.resolve(__dirname, "../assets/colleges");
const out = path.resolve(__dirname, "../data/collegeImages.js");
const ok = [".jpg", ".jpeg", ".png"];

const files = fs.existsSync(folder)
  ? fs.readdirSync(folder).filter((f) => ok.includes(path.extname(f).toLowerCase()))
  : [];

const photos = [];
const logos = [];
for (const f of files) {
  const base = path.basename(f, path.extname(f));
  if (base.endsWith("-logo")) logos.push([base.slice(0, -5), f]);
  else photos.push([base, f]);
}

const toLines = (list) =>
  list.map(([id, f]) => `  "${id}": require("../assets/colleges/${f}"),`).join("\n");

const text = `// AUTO-GENERATED by scripts/makeCollegeImages.cjs. Do not edit by hand.
export const collegePhotos = {
${toLines(photos)}
};

export const collegeLogos = {
${toLines(logos)}
};

export function getCollegeImage(college) {
  const local = collegePhotos[college.id];
  if (local) return local;
  return college.imageUrl ? { uri: college.imageUrl } : null;
}

export function getCollegeLogo(college) {
  const local = collegeLogos[college.id];
  if (local) return local;
  return college.logoUrl ? { uri: college.logoUrl } : null;
}
`;

fs.writeFileSync(out, text);
console.log("Wrote data/collegeImages.js:", photos.length, "photos,", logos.length, "logos");